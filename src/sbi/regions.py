"""Ключ субъекта РФ по названию.

Росстат, СберИндекс и справочник МО пишут субъекты по-разному: «г. Москва»
и «Москва», «Кемеровская область - Кузбасс» и «Кемеровская область»,
«Ханты-Мансийский автономный округ - Югра» и «Ханты-Мансийский авт. округ».
Ключ — первое содержательное слово названия в нижнем регистре; несколько
исключений, где первое слово не различает субъекты, заданы явно.
"""
from __future__ import annotations

import re

_SKIP = {"республика", "респ", "область", "обл", "край", "автономный", "автономная", "авт",
         "округ", "ао", "г", "город", "федерального", "значения", "российская", "федерация",
         "кроме", "без", "и", "в", "том", "числе", "чувашская", "кабардино", "карачаево"}
_LAT = str.maketrans("aceopxyhkmtbABCEHKMOPTXY", "асеорхункмтвАВСЕНКМОРТХУ")
_SPECIAL = {
    "кабардино-балкарская": "кабардино", "карачаево-черкесская": "карачаево",
    "чувашская": "чувашия", "чувашия": "чувашия",
    "ханты-мансийский": "ханты", "ямало-ненецкий": "ямало", "ненецкий": "ненецкий",
    "северная": "осетия", "осетия": "осетия",
}


def key(name: str) -> str:
    n = str(name).translate(_LAT).lower().replace("ё", "е")
    n = re.sub(r"\(.*?\)", " ", n)
    n = n.split(" - ")[0].split(" — ")[0]
    for word in re.findall(r"[а-я]+(?:-[а-я]+)?", n):
        if word in _SPECIAL:
            return _SPECIAL[word]
        base = word.split("-")[0]
        if word not in _SKIP and base not in _SKIP:
            return base
    return n.strip()

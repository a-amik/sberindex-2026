const pct = (x: number) => `${Math.floor(x)}`.replace('-', '−')
const f1 = (x: number) => x.toFixed(1).replace('.', ',')
const row = (m: string, H: number) => META.byH.find((r) => r.model === m && r.H === H)
/** Снижение MAE сдаваемой модели к Prophet на горизонте H, % (вниз до целого, как в презентации). */
const gain = (H: number) => { const a = row('ensemble_strict', H), b = row('prophet_default', H); return a && b ? 100 * (1 - a.MAE / b.MAE) : NaN }
const wape = (H: number) => row('ensemble_strict', H)?.WAPE ?? NaN


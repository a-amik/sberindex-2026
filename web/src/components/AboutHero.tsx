export function AboutHero({ h }: { h: Hero }) {
  // Полноразмерная иллюстрация: фон всего верха шапки, свой вариант для светлой и тёмной темы,
  // фон картинки равен цвету карточки — шва нет. Без неё — прежняя витрина справа.
  if (h.wide) return (
    <header className="ab-hero ab-wide">
      <div className="ab-top">
        <img className="ab-bg light" src={`/about/wide/${h.wide}-light.webp`} alt="" decoding="async" onError={(e) => { e.currentTarget.style.visibility = 'hidden' }} />
        <img className="ab-bg dark" src={`/about/wide/${h.wide}-dark.webp`} alt="" decoding="async" onError={(e) => { e.currentTarget.style.visibility = 'hidden' }} />
        <div className="ab-text">
          <p className="ab-kick">О проекте · {h.kick}</p>
          <h1>{h.title}</h1>
          <p className="ab-lede">{h.lede}</p>
        </div>
      </div>
      <div className={`ab-tiles n${h.tiles.length}`}>
        {h.tiles.map(([v, l], i) => <div key={i}><b>{v}</b><span>{l}</span></div>)}
      </div>
    </header>
  )
  return (
    <header className="ab-hero">
      {h.art && <div className="ab-art"><img src={`/about/art/${h.art}.webp`} alt="" width={1200} height={1350} decoding="async"
        onError={(e) => { (e.currentTarget.parentElement as HTMLElement).hidden = true }} /></div>}
      <div className="ab-text">
        <p className="ab-kick">О проекте · {h.kick}</p>
        <h1>{h.title}</h1>
        <p className="ab-lede">{h.lede}</p>
      </div>
      <div className={`ab-tiles n${h.tiles.length}`}>
        {h.tiles.map(([v, l], i) => <div key={i}><b>{v}</b><span>{l}</span></div>)}
      </div>
    </header>
  )
}

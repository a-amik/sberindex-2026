"""Шаг 39. Матрица чувствительностей для сценариев «Что будет, если…» (ZADANIE 6.8).

Собирает в один файл коэффициенты, которые сервис использует в ручках, вместе
со статусом и источником каждого. Две оценки считаются здесь на рядах России:

* перенос инфляции в номинальные расходы: годовой прирост номинальных расходов
  РФ по категории на годовой ИПЦ компонента (Росстат, помесячные индексы с 2022,
  г/г — произведение двенадцати), наклон и его ошибка; смысл — сколько
  процентов номинального прироста даёт процент цены (1 — объём не меняется,
  меньше 1 — объём падает);
* реальная ставка: прирост реальных расходов РФ (spend_yoy_real) на реальную
  ключевую ставку с лагом 3 и 6 месяцев, 2019—2026 без ковидных целей;
  оценка корреляционная, статус «ряды РФ».

Остальные коэффициенты — из шагов 21—38 с их результатами. Выход —
data/processed/scenario_sensitivities.json и results/forward_check/sensitivities.md.

    python scripts/39_sensitivities.py
"""
from __future__ import annotations


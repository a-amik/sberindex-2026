ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/forward_check"


def pass_through() -> list[dict]:
    nat = pd.read_parquet(ROOT / "data/processed/national.parquet").set_index("period")
    cpi = pd.read_parquet(ROOT / "data/external/rosstat/cpi_regions.parquet")
    cpi = cpi[cpi.kind == "rf"].set_index("period").sort_index()
    rows = []
    for cat, col in (("Всего", "cpi_total"), ("Продовольственные товары", "cpi_food"),
                     ("Непродовольственные товары", "cpi_nonfood"), ("Услуги", "cpi_services")):
        yoy = (np.log(cpi[col] / 100).rolling(12).sum() * 100).dropna()
        d = pd.DataFrame({"cpi": yoy, "nom": nat[f"spend_yoy_nominal:{cat}"]}).dropna()
        r = stats.linregress(d.cpi, d.nom)
        rows.append({"ручка": "цены и налоги", "параметр": f"перенос ИПЦ в номинальные расходы · {cat}", "значение": round(r.slope, 2),
                     "se": round(r.stderr, 2), "n": len(d), "окно": f"{d.index.min()}…{d.index.max()}",
                     "смысл": "п.п. номинального прироста на 1 п.п. годовой инфляции компонента; объём = значение − 1",
                     "статус": "серый: на 2023—2026 знак неустойчив (непрод −0,74, всего −0,12) — общий тренд, не перенос; в сценариях перенос 1,0 по умолчанию, объём экспертно", "источник": "scripts/39_sensitivities.py"})
    return rows


def real_rate() -> list[dict]:
    nat = pd.read_parquet(ROOT / "data/processed/national.parquet").set_index("period")
    rows = []
    for cat in ("Всего", "Непродовольственные товары", "Услуги", "Продовольственные товары"):
        y = nat[f"spend_yoy_real:{cat}"]
        for lag in (3, 6):
            d = pd.DataFrame({"r": nat.real_key_rate.shift(lag), "y": y}).dropna()
            d = d[~((d.index >= "2020-03") & (d.index <= "2022-02"))]
            d = d[d.index >= "2019-01"]
            r = stats.linregress(d.r, d.y)
            rows.append({"ручка": "деньги и кредит", "параметр": f"реальная ставка (лаг {lag} мес.) → реальный прирост · {cat}", "значение": round(r.slope, 2),
                         "se": round(r.stderr, 2), "n": len(d), "окно": f"{d.index.min()}…{d.index.max()} без ковида",
                         "смысл": "п.п. реального годового прироста на 1 п.п. реальной ключевой ставки",
                         "статус": "серый: знак положительный против теории (перегрев 2023—24 поднял и ставку, и спрос) — корреляция, не причинность; как поправка отвергнута (шаги 13, 34)",
                         "источник": "scripts/39_sensitivities.py"})
    return rows


